import React, { useState } from 'react';
import {
  Clock,
  Shield,
  HelpCircle,
  CheckCircle2,
  GitBranch,
  Edit3,
  Lock,
} from 'lucide-react';
import { Modal } from '../ui/Modal';
import { Button } from '../ui/Button';
import { Badge } from '../ui/Badge';
import { Tooltip } from '../ui/Tooltip';
import { useToast } from '../ui/Toast';
import { api } from '../../lib/api';

export interface PlanStep {
  id: string;
  name: string;
  tool: string;
  action: string;
  input: Record<string, unknown>;
  depends_on: string[];
  requires_approval: boolean;
  risk_level: 'low' | 'medium' | 'high';
  expected_output: string;
  verification_method: string;
  reason: string;
  estimated_seconds: number;
  idempotent: boolean;
}

export interface PlanData {
  title: string;
  objective: string;
  preserved_original_instruction: string;
  estimated_total_seconds: number;
  risk_level: 'low' | 'medium' | 'high';
  steps: PlanStep[];
}

export interface PlanPreviewModalProps {
  isOpen: boolean;
  onClose: () => void;
  plan: PlanData | null;
  taskId: string | null;
  plannerUsed: 'gemini' | 'openai' | 'template';
  fallbackUsed: boolean;
  onPlanApproved: () => void;
  onEditInstruction: (instruction: string) => void;
}

export const PlanPreviewModal: React.FC<PlanPreviewModalProps> = ({
  isOpen,
  onClose,
  plan,
  taskId,
  plannerUsed,
  fallbackUsed,
  onPlanApproved,
  onEditInstruction,
}) => {
  const { addToast } = useToast();
  const [approving, setApproving] = useState(false);

  if (!plan) return null;

  const handleApprove = async () => {
    if (!taskId) return;
    setApproving(true);
    try {
      await api.approvePlan(taskId);
      addToast({
        type: 'success',
        title: 'Plan Approved',
        message: `Plan "${plan.title}" approved and queued for execution.`,
      });
      onPlanApproved();
      onClose();
    } catch (err: unknown) {
      const message = err instanceof Error ? err.message : 'Failed to approve plan';
      addToast({
        type: 'error',
        title: 'Approval Error',
        message,
      });
    } finally {
      setApproving(false);
    }
  };

  const riskBadgeVariants = {
    low: 'success' as const,
    medium: 'warning' as const,
    high: 'error' as const,
  };

  return (
    <Modal
      isOpen={isOpen}
      onClose={onClose}
      title={plan.title}
      size="xl"
      className="max-h-[90vh] flex flex-col"
    >
      <div className="space-y-6 overflow-y-auto pr-1">
        {/* Planner Header Metadata */}
        <div className="p-4 rounded-xl bg-slate-900/90 border border-slate-800 flex flex-wrap items-center justify-between gap-3 text-xs">
          <div className="flex items-center gap-2">
            <span className="text-slate-400">Generated by:</span>
            <span className="font-semibold text-white capitalize">
              {plannerUsed === 'template' ? 'Template planner' : plannerUsed}
            </span>
            {plannerUsed === 'template' && <Badge variant="demo" size="sm">DEMO</Badge>}
            {fallbackUsed && (
              <Badge variant="warning" size="sm">
                Fallback Used
              </Badge>
            )}
          </div>

          <div className="flex items-center gap-4">
            <div className="flex items-center gap-1.5 text-slate-300">
              <Clock className="w-4 h-4 text-teal-400" />
              <span>Est. {plan.estimated_total_seconds}s</span>
            </div>
            <div className="flex items-center gap-1.5">
              <Shield className="w-4 h-4 text-amber-400" />
              <Badge variant={riskBadgeVariants[plan.risk_level]} size="sm">
                {plan.risk_level} risk
              </Badge>
            </div>
          </div>
        </div>

        {/* Objective & Preserved Instruction */}
        <div className="space-y-2">
          <div className="text-xs font-semibold text-slate-400 uppercase tracking-wider">Objective</div>
          <p className="text-sm text-slate-200 bg-slate-950/60 p-3 rounded-lg border border-slate-800/80">
            {plan.objective}
          </p>
          <div className="text-[11px] text-slate-500 italic">
            Preserved instruction: &quot;{plan.preserved_original_instruction}&quot;
          </div>
        </div>

        {/* Steps DAG Pipeline */}
        <div className="space-y-3">
          <div className="text-xs font-semibold text-slate-400 uppercase tracking-wider flex items-center gap-2">
            <GitBranch className="w-4 h-4 text-teal-400" />
            <span>Execution Steps DAG ({plan.steps.length} Steps)</span>
          </div>

          <div className="space-y-3">
            {plan.steps.map((step, idx) => (
              <div
                key={step.id}
                className="p-4 rounded-xl bg-slate-950/80 border border-slate-800/90 hover:border-slate-700 transition-all space-y-2.5 relative"
              >
                <div className="flex items-start justify-between gap-3">
                  <div className="flex items-start gap-3">
                    <span className="w-6 h-6 rounded-md bg-slate-800 text-teal-400 text-xs font-mono font-bold flex items-center justify-center shrink-0 mt-0.5">
                      {idx + 1}
                    </span>
                    <div>
                      <div className="text-sm font-semibold text-white flex items-center gap-2">
                        <span>{step.name}</span>
                        {step.requires_approval && (
                          <Badge variant="warning" size="sm" className="gap-1">
                            <Lock className="w-3 h-3" />
                            <span>Approval Required</span>
                          </Badge>
                        )}
                      </div>
                      <div className="text-xs font-mono text-slate-400 mt-0.5">
                        {step.action} &bull; {step.estimated_seconds}s
                      </div>
                    </div>
                  </div>

                  <div className="flex items-center gap-2">
                    <Badge variant={riskBadgeVariants[step.risk_level]} size="sm">
                      {step.risk_level}
                    </Badge>

                    {/* Why this step tooltip */}
                    <Tooltip content={`Reason: ${step.reason}`} position="left">
                      <button
                        type="button"
                        aria-label={`Why step ${idx + 1}`}
                        className="p-1 rounded text-slate-400 hover:text-teal-300 transition-colors"
                      >
                        <HelpCircle className="w-4 h-4" />
                      </button>
                    </Tooltip>
                  </div>
                </div>

                {/* Step Details & Dependencies */}
                <div className="grid grid-cols-1 sm:grid-cols-2 gap-2 text-xs pt-1 border-t border-slate-900">
                  <div className="text-slate-400">
                    <span className="text-slate-500">Output:</span> {step.expected_output}
                  </div>
                  <div className="text-slate-400 flex items-center gap-1 sm:justify-end">
                    <span className="text-slate-500">Depends on:</span>
                    {step.depends_on.length === 0 ? (
                      <span className="font-mono text-slate-600">None (Root)</span>
                    ) : (
                      step.depends_on.map((dep) => (
                        <span
                          key={dep}
                          className="px-1.5 py-0.5 rounded bg-slate-900 border border-slate-800 text-[10px] font-mono text-teal-400"
                        >
                          {dep}
                        </span>
                      ))
                    )}
                  </div>
                </div>

                <div className="text-[11px] text-teal-300/80 bg-teal-500/5 px-2.5 py-1 rounded border border-teal-500/10">
                  <span className="font-semibold text-teal-400">Why:</span> {step.reason}
                </div>
              </div>
            ))}
          </div>
        </div>

        {/* Action Controls */}
        <div className="pt-4 border-t border-slate-800 flex flex-col sm:flex-row items-center justify-between gap-3">
          <Button
            type="button"
            variant="ghost"
            size="sm"
            onClick={() => {
              onEditInstruction(plan.preserved_original_instruction);
              onClose();
            }}
            className="gap-2 text-slate-300 hover:text-white"
          >
            <Edit3 className="w-4 h-4" />
            <span>Edit Instruction</span>
          </Button>

          <div className="flex items-center gap-3 w-full sm:w-auto">
            <Button type="button" variant="outline" size="sm" onClick={onClose}>
              Cancel
            </Button>
            <Button
              type="button"
              variant="primary"
              size="sm"
              isLoading={approving}
              onClick={handleApprove}
              className="gap-2 shadow-glow-cyan"
            >
              <CheckCircle2 className="w-4 h-4" />
              <span>Approve &amp; Queue Plan</span>
            </Button>
          </div>
        </div>
      </div>
    </Modal>
  );
};
